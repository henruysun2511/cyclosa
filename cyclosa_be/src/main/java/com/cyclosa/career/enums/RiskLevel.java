package com.cyclosa.career.enums;

public enum RiskLevel {
    LOW,        // Rủi ro thấp: dễ tuyển mới, tác động vận hành thấp
    MEDIUM,     // Rủi ro trung bình: cần 1-3 tháng bàn giao
    HIGH,       // Rủi ro cao: vị trí quản lý then chốt, khó tuyển ngoài
    CRITICAL    // Rủi ro nguy cấp: vị trí chiến lược tối cao, tổn thất lớn nếu khuyết
}
